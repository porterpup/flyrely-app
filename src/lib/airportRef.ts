export function getAirportRef(code: string): AirportRef | undefined {
  return AIRPORT_REF[code.toUpperCase()];
}

/** "Jacksonville, FL" when the city is known, else the airport name, else the code. */
export function getCityLabel(code: string): string {
  const a = getAirportRef(code);
  if (!a) return code.toUpperCase();
  if (a.city) return a.state ? `${a.city}, ${a.state}` : a.city;
  return a.name;
}

/** Full airport name, e.g. "Washington Dulles International Airport". */
export function getAirportName(code: string): string {
  return getAirportRef(code)?.name ?? code.toUpperCase();
}
