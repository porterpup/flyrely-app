#!/usr/bin/env node
// Builds src/lib/airportTz.ts (IATA -> IANA zone) from the API's airports_ref.csv.
// Usage: node scripts/gen-airport-tz.mjs [path/to/airports_ref.csv]
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const csvPath = process.argv[2] ?? resolve(root, '../flyrely-api/models/airports_ref.csv');
const lines = readFileSync(csvPath, 'utf8').split(/\r?\n/).filter(Boolean);
const header = lines[0].split(',');
const iIata = header.indexOf('iata');
const iTz = header.indexOf('tz');
if (iIata < 0 || iTz < 0) throw new Error('CSV needs iata and tz columns');

const map = new Map();
for (const line of lines.slice(1)) {
  const cols = line.split(',');
  const iata = cols[iIata]?.trim().toUpperCase();
  const tz = cols[iTz]?.trim();
  if (!/^[A-Z]{3}$/.test(iata ?? '') || !tz) continue;
  try {
    new Intl.DateTimeFormat('en-US', { timeZone: tz });
  } catch {
    console.warn(`skipping ${iata}: invalid zone ${tz}`);
    continue;
  }
  map.set(iata, tz);
}

const body = [...map.entries()]
  .sort(([a], [b]) => (a < b ? -1 : 1))
  .map(([k, v]) => `  ${k}: '${v}',`)
  .join('\n');
writeFileSync(
  resolve(root, 'src/lib/airportTz.ts'),
  `// Generated by scripts/gen-airport-tz.mjs — do not edit.\n/** IATA airport code -> IANA time zone. */\nexport const AIRPORT_TZ: Record<string, string> = {\n${body}\n};\n`
);
console.log(`wrote ${map.size} airports`);
